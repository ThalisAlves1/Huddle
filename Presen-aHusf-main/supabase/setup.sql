create extension if not exists pgcrypto;

create type public.perfil_usuario as enum ('COLABORADOR', 'LIDER', 'ADMIN');
create type public.status_huddle as enum ('AGENDADO', 'EM_ANDAMENTO', 'ENCERRADO', 'CANCELADO');
create type public.status_presenca as enum ('PRESENTE', 'ATRASADO');

create table if not exists public.setores (
  id uuid primary key default gen_random_uuid(),
  nome text not null unique,
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  matricula text not null unique,
  email text,
  perfil public.perfil_usuario not null default 'COLABORADOR',
  setor_id uuid references public.setores(id),
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists public.huddles (
  id uuid primary key default gen_random_uuid(),
  codigo text not null unique,
  titulo text not null,
  setor_id uuid references public.setores(id),
  responsavel_id uuid not null references public.profiles(id),
  status public.status_huddle not null default 'AGENDADO',
  data_local date not null default current_date,
  iniciado_em timestamptz,
  encerrado_em timestamptz,
  expira_em timestamptz,
  duracao_minutos integer not null default 30,
  atraso_apos_minutos integer not null default 10,
  qr_payload text unique,
  criado_em timestamptz not null default now()
);

create table if not exists public.presencas (
  id uuid primary key default gen_random_uuid(),
  huddle_id uuid not null references public.huddles(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  status public.status_presenca,
  aceite boolean,
  aceite_em timestamptz,
  aceite_texto text,
  aceite_versao text,
  confirmado_em timestamptz,
  criado_em timestamptz not null default now(),
  unique (huddle_id, user_id)
);

create table if not exists public.auditoria_huddle (
  id bigint generated by default as identity primary key,
  huddle_id uuid references public.huddles(id) on delete cascade,
  tabela text not null,
  acao text not null,
  usuario_id uuid references public.profiles(id),
  detalhes jsonb not null default '{}'::jsonb,
  ocorrido_em timestamptz not null default now()
);

create table if not exists public.evidencias_pdf (
  id uuid primary key default gen_random_uuid(),
  huddle_id uuid not null references public.huddles(id) on delete cascade,
  hash_sha256 text not null,
  nome_arquivo text not null,
  tamanho_bytes bigint not null,
  criado_por uuid references public.profiles(id),
  criado_em timestamptz not null default now(),
  unique (huddle_id, hash_sha256)
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, nome, matricula, email, perfil, setor_id)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'nome', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'matricula', 'PENDENTE-' || substr(new.id::text, 1, 8)),
    new.email,
    'COLABORADOR',
    nullif(new.raw_user_meta_data ->> 'setor_id', '')::uuid
  )
  on conflict (id) do update set email = excluded.email;
  return new;
exception when unique_violation then
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at before update on public.profiles
for each row execute procedure public.set_updated_at();

