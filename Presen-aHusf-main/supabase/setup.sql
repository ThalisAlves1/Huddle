create or replace function public.get_home_colaborador()
returns json
language sql stable security definer set search_path = public
as $$
  select json_build_object(
    'nome', p.nome,
    'matricula', p.matricula,
    'perfil', p.perfil,
    'setor_id', p.setor_id,
    'setor_nome', s.nome,
    'huddle_id', h.id,
    'huddle_codigo', h.codigo,
    'huddle_titulo', h.titulo,
    'huddle_status', h.status,
    'huddle_data', h.data_local,
    'iniciado_em', h.iniciado_em,
    'atraso_apos', case when h.iniciado_em is null then null else h.iniciado_em + make_interval(mins => h.atraso_apos_minutos) end,
    'expira_em', h.expira_em,
    'presenca_id', pr.id,
    'presenca_status', pr.status,
    'confirmado_em', pr.confirmado_em
  )
  from public.profiles p
  left join public.setores s on s.id = p.setor_id
  left join lateral (
    select * from public.huddles h0
    where h0.status in ('AGENDADO', 'EM_ANDAMENTO')
    order by h0.criado_em desc limit 1
  ) h on true
  left join public.presencas pr on pr.huddle_id = h.id and pr.user_id = p.id
  where p.id = auth.uid();
$$;

grant execute on function public.get_home_colaborador() to authenticated;

create or replace function public.validar_qr_huddle(p_payload text)
returns json
language plpgsql security definer set search_path = public
as $$
declare r public.huddles;
begin
  select * into r from public.huddles where qr_payload = p_payload;
  if not found then raise exception 'QR Code invalido.'; end if;
  return json_build_object(
    'huddle_id', r.id, 'codigo', r.codigo, 'titulo', r.titulo,
    'setor_nome', (select nome from public.setores where id = r.setor_id),
    'data_local', r.data_local, 'iniciado_em', r.iniciado_em,
    'expira_em', r.expira_em,
    'ja_confirmado', exists(select 1 from public.presencas where huddle_id = r.id and user_id = auth.uid())
  );
end;
$$;

grant execute on function public.validar_qr_huddle(text) to authenticated;

create or replace function public.confirmar_presenca_huddle(p_payload text, p_aceite boolean)
returns json
language plpgsql security definer set search_path = public
as $$
declare r public.huddles; v_status public.status_presenca;
begin
  select * into r from public.huddles where qr_payload = p_payload;
  if not found then raise exception 'QR Code invalido.'; end if;
  if r.status not in ('EM_ANDAMENTO', 'AGENDADO') then raise exception 'Este Huddle nao esta disponivel.'; end if;
  v_status := case when r.iniciado_em is not null and now() > r.iniciado_em + make_interval(mins => r.atraso_apos_minutos) then 'ATRASADO' else 'PRESENTE' end;
  insert into public.presencas (huddle_id, user_id, status, aceite, aceite_em, confirmado_em, aceite_texto, aceite_versao)
  values (r.id, auth.uid(), v_status, p_aceite, now(), now(), 'Confirmo minha participacao no Huddle.', '1.0')
  on conflict (huddle_id, user_id) do update set status = excluded.status, aceite = excluded.aceite, aceite_em = now(), confirmado_em = now();
  return json_build_object('huddle_id', r.id, 'status', v_status, 'confirmado_em', now());
end;
$$;

grant execute on function public.confirmar_presenca_huddle(text, boolean) to authenticated;

